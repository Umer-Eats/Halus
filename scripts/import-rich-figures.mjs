// Wikimedia Commons figures for the in-depth courses, with licence and author checked.
//   node scripts/import-rich-figures.mjs --search "dental explorer instrument" ...
//     lists matching Commons files with their licence, so a lesson can cite one.
//   node scripts/import-rich-figures.mjs
//     finds every {t:'fig', file:'File:…'} used in dist/rich/*.js, verifies it is public
//     domain, CC0, CC BY or CC BY-SA, and writes dist/rich/figures.js with the credit line.
import fs from 'node:fs/promises';

const API = 'https://commons.wikimedia.org/w/api.php';
const HEADERS = { 'user-agent': 'ValusCourseBuilder/1.0 (educational, non-commercial; https://valus.app)' };
const OPEN = /^(public domain|pd\b|pd-|cc0|cc by(-sa)? \d|cc-by(-sa)?-\d|attribution)/i;
const clean = s => String(s || '').replace(/<[^>]*>/g, ' ').replace(/&amp;/g, '&').replace(/&quot;/g, '"').replace(/&#0?39;|&#x27;/g, "'").replace(/\s+/g, ' ').trim();

async function api(params) {
  const url = API + '?' + new URLSearchParams({ format: 'json', origin: '*', ...params });
  for (let attempt = 0; attempt < 3; attempt++) {
    const r = await fetch(url, { headers: HEADERS, signal: AbortSignal.timeout(25000) }).catch(() => null);
    if (r?.ok) return r.json();
    await new Promise(res => setTimeout(res, 1500));
  }
  throw Error('Commons API unavailable');
}

async function info(titles) {
  const out = {};
  for (let i = 0; i < titles.length; i += 40) {
    const j = await api({ action: 'query', titles: titles.slice(i, i + 40).join('|'), prop: 'imageinfo', iiprop: 'url|extmetadata|mime|size', iiurlwidth: '960' });
    const normal = Object.fromEntries((j.query.normalized || []).map(n => [n.to, n.from]));
    for (const p of Object.values(j.query.pages)) {
      const ii = p.imageinfo?.[0], m = ii?.extmetadata || {};
      out[normal[p.title] || p.title] = ii && {
        url: ii.thumburl || ii.url, width: ii.thumbwidth || ii.width, height: ii.thumbheight || ii.height, mime: ii.mime,
        source: ii.descriptionurl, author: clean(m.Artist?.value) || 'Unknown author',
        license: clean(m.LicenseShortName?.value), licenseUrl: m.LicenseUrl?.value || ii.descriptionurl,
        description: clean(m.ImageDescription?.value).slice(0, 300),
      };
    }
  }
  return out;
}

if (process.argv[2] === '--search') {
  for (const query of process.argv.slice(3)) {
    const j = await api({ action: 'query', list: 'search', srnamespace: '6', srlimit: '14', srsearch: query });
    const titles = j.query.search.map(s => s.title);
    const meta = await info(titles);
    console.log('## ' + query);
    for (const t of titles) {
      const m = meta[t];
      if (!m || !/^image\//.test(m.mime)) continue;
      console.log(`${OPEN.test(m.license) ? 'OK ' : 'NO '} ${t}  [${m.license}] ${m.width}x${m.height}  ${m.description.slice(0, 110)}`);
    }
  }
} else {
  const dir = new URL('../dist/rich/', import.meta.url);
  const files = new Set();
  for (const name of await fs.readdir(dir)) {
    if (!name.endsWith('.js') || name === 'figures.js') continue;
    const text = await fs.readFile(new URL(name, dir), 'utf8');
    for (const m of text.matchAll(/file:\s*'(File:[^']+)'/g)) files.add(m[1]);
  }
  const meta = await info([...files]);
  const out = {}, problems = [];
  for (const file of [...files].sort()) {
    const m = meta[file];
    if (!m) { problems.push('missing ' + file); continue; }
    if (!OPEN.test(m.license)) { problems.push(`licence ${m.license} ${file}`); continue; }
    out[file] = { url: m.url, width: m.width, height: m.height, source: m.source, credit: m.author, license: m.license, licenseUrl: m.licenseUrl };
  }
  if (problems.length) { console.error(problems.join('\n')); process.exitCode = 1; }
  await fs.writeFile(new URL('figures.js', dir), '// Generated by scripts/import-rich-figures.mjs from Wikimedia Commons. Every file is public domain, CC0, CC BY or CC BY-SA and is credited where shown.\nexport const FIGURES = ' + JSON.stringify(out, null, 1) + ';\n');
  console.log(Object.keys(out).length + ' figures written');
}
