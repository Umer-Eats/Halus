// Imports OpenStax figures for the in-depth lessons into dist/rich/figures.js.
//   node scripts/import-openstax-figures.mjs                 write figures.js for every figure in dist/rich/figure-places.js
//   node scripts/import-openstax-figures.mjs --list book/page [book/page …]   list a page's figures
// Each figure is taken by its number on the page, only from pages under a Creative Commons
// licence, and checked to exist. Lessons reference figures as {t:'fig', file:'<key>', caption, alt}.
import fs from 'node:fs/promises';
import {FIGURE_PLACES, figureKey} from '../dist/rich/figure-places.js';

const BOOKS = {
  'anatomy-and-physiology': 'OpenStax Anatomy and Physiology',
  'psychology': 'OpenStax Psychology',
  'psychology-2e': 'OpenStax Psychology 2e',
  'microbiology': 'OpenStax Microbiology',
  'college-physics-2e': 'OpenStax College Physics 2e',
  'biology-2e': 'OpenStax Biology 2e',
};

// Every figure placed in a lesson, once: key → [book, page, figure number].
const FIGURES = {};
for (const lessons of Object.values(FIGURE_PLACES)) for (const list of Object.values(lessons)) for (const [, ref, number] of list) {
  const [book, slug] = ref.split('/');
  FIGURES[figureKey(ref, number)] = [book, slug, number];
}

const LICENSES = [
  ['creativecommons.org/licenses/by/4.0/', 'CC BY 4.0', 'https://creativecommons.org/licenses/by/4.0/'],
  ['creativecommons.org/licenses/by-nc-sa/4.0/', 'CC BY-NC-SA 4.0', 'https://creativecommons.org/licenses/by-nc-sa/4.0/'],
];
const clean = s => s.replace(/<[^>]*>/g, ' ').replace(/&amp;/g, '&').replace(/&quot;/g, '"').replace(/&#x27;|&#39;/g, "'").replace(/\s+/g, ' ').trim();
const pages = new Map();

async function page(book, slug) {
  const url = `https://openstax.org/books/${book}/pages/${slug}`;
  if (pages.has(url)) return pages.get(url);
  let html = null;
  for (let i = 0; i < 3 && !html; i++) {
    const res = await fetch(url, {signal: AbortSignal.timeout(25000)}).catch(() => null);
    if (res?.ok) html = await res.text();
  }
  if (!html) throw new Error('Unavailable: ' + url);
  const license = LICENSES.find(([needle]) => html.includes(needle));
  if (!license) throw new Error('No Creative Commons licence found: ' + url);
  const figures = [...html.matchAll(/<figure[\s\S]*?<\/figure>/g)].map(([m]) => {
    const img = m.match(/<img[^>]*data-media-type[^>]*>/)?.[0] || '';
    return {
      number: clean(m.match(/class="os-number">([\s\S]*?)<\/span>/)?.[1] || ''),
      title: clean(m.match(/class="os-title"[^>]*>([\s\S]*?)<\/span>/)?.[1] || ''),
      alt: clean(img.match(/alt="([^"]*)"/)?.[1] || ''),
      src: img.match(/data-original-src="([^"]+)"/)?.[1] || img.match(/src="([^"]+)"/)?.[1],
      width: Number(img.match(/width="(\d+)"/)?.[1]) || 0,
      height: Number(img.match(/height="(\d+)"/)?.[1]) || 0,
    };
  }).filter(f => f.number && f.src);
  const result = {url, license, figures};
  pages.set(url, result);
  return result;
}

if (process.argv[2] === '--list') {
  for (const ref of process.argv.slice(3)) {
    const [book, slug] = ref.split('/');
    try { const p = await page(book, slug); console.log(`# ${ref} (${p.license[1]})`); p.figures.forEach(f => console.log(`  ${f.number}  ${f.title || '(' + f.alt.slice(0, 110) + ')'}`)); }
    catch (error) { console.log('! ' + error.message); }
  }
} else {
  const out = {};
  for (const [key, [book, slug, number]] of Object.entries(FIGURES)) {
    const p = await page(book, slug);
    const f = p.figures.find(x => x.number === number);
    if (!f) throw new Error(`Figure ${number} not found on ${p.url}`);
    const url = new URL(f.src, 'https://openstax.org').href;
    const head = await fetch(url, {method: 'HEAD', signal: AbortSignal.timeout(20000)}).catch(() => null);
    if (!head?.ok || !head.headers.get('content-type')?.startsWith('image/')) throw new Error('Image unavailable: ' + url);
    out[key] = {url, width: f.width, height: f.height, credit: `${BOOKS[book] || 'OpenStax'}, Figure ${number}${f.title ? ` (${f.title})` : ''}, OpenStax / Rice University`, source: p.url, license: p.license[1], licenseUrl: p.license[2]};
    console.log('ok', key, number, f.title);
  }
  await fs.writeFile(new URL('../dist/rich/figures.js', import.meta.url), `// Generated by scripts/import-openstax-figures.mjs. Figures from OpenStax textbooks under Creative Commons licences, credited where shown.\nexport const FIGURES = ${JSON.stringify(out, null, 1)};\n`);
  console.log(Object.keys(out).length, 'figures written');
}
